    /// Validate the bundled config against the *real* installed zellij — this is
    /// what catches a malformed keybinds block (a bogus action name or mode),
    /// which `cargo` cannot. Skips gracefully when zellij isn't installed (CI
    /// without it). Note: `setup --check` validates *parse-correctness*, not the
    /// runtime keymap merge, so it guards regressions in the config's validity,
    /// not the live unlock behaviour (which needs a human at a tty).
    #[test]
    fn config_passes_zellij_setup_check() {
        if Command::new("zellij").arg("--version").output().is_err() {
            eprintln!("skipping config_passes_zellij_setup_check: zellij not installed");
            return;
        }
        let dir = tempfile::tempdir().expect("tempdir");
        // Write the real bundled plugin so the config's `file:` alias points at an
        // existing artifact, then render + validate exactly what launch() writes.
        let wasm = dir.path().join("grove-nav.wasm");
        std::fs::write(&wasm, NAV_WASM).expect("write nav wasm");
        let cfg = dir.path().join("config.kdl");
        std::fs::write(&cfg, render_config(&wasm)).expect("write config");
        let out = Command::new("zellij")
            .arg("--config")
            .arg(&cfg)
            .args(["setup", "--check"])
            .output()
            .expect("running zellij setup --check");
        let combined = format!(
            "{}{}",
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        );
        assert!(
            combined.contains("Well defined"),
            "zellij rejected the bundled config:\n{combined}"
        );
    }

    #[test]
    fn cache_dir_prefers_xdg_then_home() {
        let xdg = cache_dir_from(Some(OsStr::new("/x/cache")), Some(OsStr::new("/home/u"))).unwrap();
        assert_eq!(xdg, PathBuf::from("/x/cache/grove/zellij"));

        // Empty XDG_CACHE_HOME is treated as unset → HOME fallback.
        let home = cache_dir_from(Some(OsStr::new("")), Some(OsStr::new("/home/u"))).unwrap();
        assert_eq!(home, PathBuf::from("/home/u/.cache/grove/zellij"));

        let none = cache_dir_from(None, Some(OsStr::new("/home/u"))).unwrap();
        assert_eq!(none, PathBuf::from("/home/u/.cache/grove/zellij"));
    }

    #[test]
    fn cache_dir_errors_without_any_env() {
        assert!(cache_dir_from(None, None).is_err());
        assert!(cache_dir_from(Some(OsStr::new("")), Some(OsStr::new(""))).is_err());
    }

    #[test]
    fn session_name_sanitises_and_namespaces() {
        assert_eq!(session_name(Path::new("/work/grove")), "grove-grove");
        assert_eq!(session_name(Path::new("/work/my repo.git")), "grove-my-repo-git");
        // A basename that sanitises to nothing falls back to plain `grove`.
        assert_eq!(session_name(Path::new("/work/...")), "grove");
    }
